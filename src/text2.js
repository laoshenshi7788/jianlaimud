/* ── 工具 ───────────────────────────────────────────────────── */
function jl2_textErr(e){
  try{
    if(!window.__bootErrs) window.__bootErrs=[];
    window.__bootErrs.push('[text2] '+(e&&e.message?e.message:String(e)));
  }catch(_){}
}
function jl2_textFill(s,v){
  if(typeof s!=='string') return s;
  return s.replace(/\$\{(\w+)\}/g,function(_,k){ return v[k]==null?'':v[k]; });
}
function jl2_textCap(s){
  s=String(s==null?'':s);
  return s.length>42?s.slice(0,39)+'……':s;
}
function jl2_textNorm(s){
  s=String(s==null?'':s);
  return s.replace(/^（[^）]*）/,'').replace(/[（(][^）)]*[）)]/g,'').trim();
}
function jl2_textNpc(g){
  g=String(g==null||g===''?'对方':g);
  return g.replace(/(私塾先生|坐堂郎中|账房先生|说书人|镇民|掌柜|伙计|茶博士)$/,'')||g;
}

