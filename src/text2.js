/* 对外清理函数：供运行时 log/emit 调用方按需过滤 */
function jl2_textClean(s){
  if(typeof s!=='string') return s;
  var out=s;
  for(var j=0;j<JL2_TEXT_JUNK.length;j++) out=out.split(JL2_TEXT_JUNK[j]).join('');
  for(var k in JL2_TEXT_LOG_FIX){
    if(Object.prototype.hasOwnProperty.call(JL2_TEXT_LOG_FIX,k) && out.indexOf(k)>-1){
      out=out.split(k).join(JL2_TEXT_LOG_FIX[k]);
    }
  }
  return out;
}

