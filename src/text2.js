/* ── 安装：label 与 type 对齐 ───────────────────────────────── */
function jl2_textFixNodes(list){
  if(!list||!list.length) return;
  for(var i=0;i<list.length;i++){
    try{
      var s=list[i]; if(!s||!s.type) continue;
      var prefix=JL2_TEXT_LABEL_PREFIX[s.type];
      if(!prefix) continue;
      var cur=String(s.label==null?'':s.label);
      // 已是语义一致：label 含目标物关键词，或以本类型前缀打头（幂等）
      var what=String(s.what||s.item||s.npc||s.enemy||s.room||'');
      if(cur.indexOf(prefix)===0 && cur.indexOf(what)>-1) continue;
      var short=what;
      if(String(what).indexOf('·')>-1){
        var parts=String(what).split('·');
        short=parts[parts.length-1];                        // 房间取末段
      }
      if(short.length>8) short=short.slice(0,8);
      var want=prefix+(short||s.type);
      if(want!==cur){ s.label=want; JL2_TEXT_STAT.label++; }
    }catch(e){ jl2_textErr(e); }
  }
}
