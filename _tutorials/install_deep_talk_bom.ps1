function openDeepTalk(npcName){
  const list=NPC_DEEP[npcName]; if(!list) return;
  if(!game.deepTalk) game.deepTalk={};
  const heard=game.deepTalk[npcName]||[];
  const h=document.createElement('div');
  const head=document.createElement('div');
  head.style.cssText='font-size:.78em;color:#c6bca6;line-height:1.8;margin-bottom:10px;';
  head.textContent='与'+npcName+'深谈——听得越多，越是交心。（听新话题可增进交情）';
  h.appendChild(head);
  const pane=document.createElement('div');
  pane.style.cssText='border:1px solid var(--line-soft);border-radius:8px;padding:12px 14px;min-height:120px;font-size:.9em;line-height:2;color:#ece5d3;background:rgba(255,255,255,.02);';
  pane.textContent='（挑一个话题，听'+npcName+'慢慢道来。）';
  h.appendChild(pane);
  const listEl=document.createElement('div');
  listEl.style.cssText='margin-top:10px;display:flex;flex-direction:column;gap:6px;';
  list.forEach(function(tp,i){
    const isHeard=heard.includes(i);
    const gated=(tp.need||0)>(player.aff[npcName]||0);
    const b=document.createElement('button');
    b.className='btn small '+(isHeard?'':(gated?'':'blue'));
    b.style.cssText='text-align:left;'+(gated?'opacity:.45;':'');
    b.innerHTML=(isHeard?'✔ ':'')+tp.t+(gated?'（交情尚浅）':'');
    if(!gated){
      b.addEventListener('click',function(){
        pane.innerHTML='<div style="font-weight:bold;letter-spacing:2px;margin-bottom:6px;color:#f0cf8f;">【'+tp.t+'】</div>'+tp.text.replace(/\\n/g,'<br>');
        if(!heard.includes(i)){
          heard.push(i);
          game.deepTalk[npcName]=heard;
          player.aff[npcName]=(player.aff[npcName]||0)+2;
          player.exp+=8;
          logSuccess('（与'+npcName+'深谈「'+tp.t+'」，交情 +2，见闻 +8。）');
          updateSidebar();
        }
        const tip=pane.querySelector('.deep-new'); if(tip) tip.remove();
      });
    }
    listEl.appendChild(b);
  });
  h.appendChild(listEl);
  const close=document.createElement('button');
  close.className='btn small'; close.style.cssText='margin-top:10px;'; close.textContent='告辞';
  close.addEventListener('click',function(){ document.getElementById('overlay').classList.remove('show'); });
  h.appendChild(close);
  openModal(npcName+' · 深谈', ()=>h);
}

